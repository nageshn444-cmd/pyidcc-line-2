const LOCAL_STORAGE_KEY = "pyidcc_als_nomination_master_2026";

export function getStoredMentors() {
  if (typeof window === "undefined" || !window.localStorage) {
    return OFFICIAL_ALS_MENTORS;
  }
  try {
    const raw = window.localStorage.getItem(LOCAL_STORAGE_KEY);
    if (!raw) {
      window.localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(OFFICIAL_ALS_MENTORS));
      return OFFICIAL_ALS_MENTORS;
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length >= 3) {
      return parsed;
    }
  } catch (err) {
    console.warn("Failed to read mentor registry cache:", err);
  }
  return OFFICIAL_ALS_MENTORS;
}

export function saveMentors(mentors) {
  if (typeof window !== "undefined" && window.localStorage) {
    try {
      window.localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(mentors));
      window.dispatchEvent(new CustomEvent("pyidcc_mentors_updated", { detail: { mentors } }));
    } catch (err) {
      console.warn("Failed to save mentor registry cache:", err);
    }
  }
}

export function getMentorByName(mentorName) {
  const list = getStoredMentors();
  const search = String(mentorName || "").toUpperCase().trim();
  const found = list.find(m => 
    String(m.name).toUpperCase().trim() === search || 
    String(m.displayName).toUpperCase().includes(search) ||
    String(m.id) === search
  );
  if (found) return found;

  const sub = list.find(m => search.includes(String(m.name).toUpperCase()) || String(m.name).toUpperCase().includes(search));
  return sub || list[0];
}

export function getMentorAssignedOperators(mentorName) {
  const mentor = getMentorByName(mentorName);
  return mentor ? mentor.assignedOperators || [] : [];
}

export function updateMentorAssignedOperators(mentorName, operators) {
  const list = getStoredMentors();
  const search = String(mentorName || "").toUpperCase().trim();
  const updated = list.map(m => {
    if (String(m.name).toUpperCase().trim() === search || String(m.displayName).toUpperCase().includes(search)) {
      return { ...m, assignedOperators: operators };
    }
    return m;
  });
  saveMentors(updated);
  return updated;
}
