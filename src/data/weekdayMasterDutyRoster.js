/**
 * Returns the official assigned Train Operator for a given duty ID.
 * @param {string|number} dutyId 
 * @returns {{ dutyId: string, empId: string, empName: string, designation: string }}
 */
export function getOperatorForDuty(dutyId) {
  if (!dutyId) return null;
  const clean = String(dutyId).replace(/^duty[_s-]*/i, '').trim();
  const norm = clean.padStart(2, '0');
  return WEEKDAY_MASTER_DUTY_ROSTER[norm] || WEEKDAY_MASTER_DUTY_ROSTER[clean] || null;
}
