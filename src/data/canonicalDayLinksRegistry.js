export { WEEKDAY_MASTER_LINKS };

export function getMasterLinksForDay(dayType = "WEEKDAY") {
  const norm = normalizeScheduleDay(dayType);
  if (norm === "SATURDAY") return SATURDAY_MASTER_LINKS;
  if (norm === "SUNDAY") return SUNDAY_MASTER_LINKS;
  if (norm === "MONDAY") return MONDAY_MASTER_LINKS;
  return WEEKDAY_MASTER_LINKS;
}

export function buildCanonicalDutiesForDate(dayType = "WEEKDAY", targetDate = null, includeDefaultOperators = false) {
  const dateStr = targetDate || new Date().toISOString().split("T")[0];
  const normDay = normalizeScheduleDay(dayType);
  const links = getMasterLinksForDay(normDay);

  return links.map(link => {
    const rawDuty = String(link.dutyId || link.dutyNo || "").trim();
    const crMatch = rawDuty.match(/^CR(\d+)$/i);
    let normDuty = rawDuty;
    if (crMatch) {
      const num = parseInt(crMatch[1], 10);
      normDuty = `CR${num < 10 ? '0' + num : num}`;
    } else if (/^[0-9]$/.test(rawDuty)) {
      normDuty = "0" + rawDuty;
    }
    const defaultOp = includeDefaultOperators ? getOperatorForDuty(normDuty) : null;

    return {
      id: "gcc_deploy_" + normDay.toLowerCase() + "_duty_" + normDuty,
      dutyId: normDuty,
      dutyNo: normDuty,
      date: dateStr,
      targetDate: dateStr,
      deploymentDate: dateStr,
      scheduleType: normDay,
      trainId: link.trainId || link.leg1TrainNo || "--",
      signOnTime: link.signOnTime || "06:00:00",
      signOnLocation: link.signOnLocation || "PYID",
      signOffTime: link.signOffTime || "14:00:00",
      signOffLocation: link.signOffLocation || "PYID",
      empId: link.empId || defaultOp?.empId || "--",
      empName: link.empName || defaultOp?.empName || "--",
      status: includeDefaultOperators ? "AUTHORIZED_OK" : "PENDING",
      remarks: link.remarks || ("Official " + normDay + " Link Roster"),
      rawLegs: {
        l1Train: link.leg1TrainNo || link.trainId || "--",
        l1Start: link.leg1TimeFrom || link.signOnTime || "--",
        l1End: link.leg1TimeTo || "--",
        l2Train: link.leg2TrainNo || "--",
        l2Start: link.leg2DepTime || "--",
        l2End: link.leg2ArrTime || "--",
        l3Train: link.leg3TrainNo || "--",
        l3Start: link.leg3DepTime || "--",
        l3End: link.leg3ArrTime || "--",
        l4Train: link.leg4TrainNo || "--",
        l4Start: link.leg4FinalDepTime || "--",
        l4End: link.leg4FinalArrTime || "--"
      }
    };
  });
}
