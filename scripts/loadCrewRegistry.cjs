// Parse CSV with robust quote handling
function parseCSV(csv) {
  const lines = csv.split('\n');
  const headers = lines[0].split(',').map(h => h.trim().toLowerCase());
  
  const empCodeIdx = headers.findIndex(h => h === 'emp code' || h === 'emp id');
  const nameIdx = headers.findIndex(h => h === 'name');
  const designationIdx = headers.findIndex(h => h === 'designation');
  const cugIdx = headers.findIndex(h => h === 'mobile-cug');
  const perIdx = headers.findIndex(h => h === 'mobile-per');
  const emailIdx = headers.findIndex(h => h === 'email');

  const members = [];
  const seen = new Set();

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    // Parse handling quoted fields
    const row = [];
    let inQuotes = false, current = '';
    for (let j = 0; j < line.length; j++) {
      const ch = line[j];
      if (ch === '"') { inQuotes = !inQuotes; }
      else if (ch === ',' && !inQuotes) { row.push(current.trim()); current = ''; }
      else { current += ch; }
    }
    row.push(current.trim());

    const id = row[empCodeIdx];
    if (!id || isNaN(Number(id))) continue;
    if (seen.has(id)) continue;
    seen.add(id);

    const name = (row[nameIdx] || '').replace(/"/g, '').trim();
    const rawDesig = (row[designationIdx] || '').trim();
    
    // Normalize designation
    let designation = 'Station Controller / Train Operator';
    if (rawDesig.toLowerCase().includes('station superintendent')) {
      designation = 'Station Superintendent';
    }

    // Pick best contact: CUG first, then personal, skip NO/empty
    const cug = (row[cugIdx] || '').replace(/NO/i, '').trim();
    const per = (row[perIdx] || '').replace(/NO/i, '').trim();
    const contact = cug || per;

    const email = (row[emailIdx] || '').replace(/NO/i, '').trim();

    members.push({ id, name, designation, contact, email });
  }

  // Sort by ID numerically
  members.sort((a, b) => Number(a.id) - Number(b.id));
  return members;
}

